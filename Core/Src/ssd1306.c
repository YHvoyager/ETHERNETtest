#define FONT_FIRST  0x20
#define FONT_LAST   0x7E
#define FONT_COUNT  ((uint32_t)(FONT_LAST - FONT_FIRST + 1))

/** @brief 取字模；不在表里的字符返回 NULL，调用者用空格或方块代替 */
static const glyph_t *font_lookup(char c)
{
  uint32_t i;

  for (i = 0UL; i < (uint32_t)(sizeof(s_font) / sizeof(s_font[0])); i++)
  {
    if (s_font[i].ch == c)
    {
      return &s_font[i];
    }
  }
  return NULL;
}

/** @brief 画一个实心方块（字库里没有的字符用它占位） */
static void draw_block(uint8_t x, uint8_t y, uint8_t on)
{
  uint8_t i;
  uint8_t j;

  for (i = 0U; i < 7U; i++)
  {
    for (j = 0U; j < 14U; j++)
    {
      SSD1306_DrawPixel((uint8_t)(x + i), (uint8_t)(y + j), on);
    }
  }
}

void SSD1306_DrawChar(uint8_t x, uint8_t y, char c, uint8_t on)
{
  const glyph_t *g;
  uint8_t        i;

  if ((uint8_t)c > FONT_LAST)
  {
    /* 非 ASCII（UTF-8 汉字的首字节 ≥ 0xE0 会走到这里）：画个方块，
     * 让人一眼看出"这里有个字，但字库没有"，而不是安静地什么都不画。 */
    draw_block(x, y, on);
    return;
  }

  g = font_lookup(c);
  if (g == NULL)
  {
    draw_block(x, y, on);
    return;
  }

  /* 一个字横跨 2 页：上半页 8 列 + 下半页 8 列 */
  for (i = 0U; i < 8U; i++)
  {
    uint8_t row;

    for (row = 0U; row < 8U; row++)
    {
      SSD1306_DrawPixel((uint8_t)(x + i), (uint8_t)(y + row),
                        (uint8_t)((g->col[i] >> row) & 1U));
      SSD1306_DrawPixel((uint8_t)(x + i), (uint8_t)(y + 8U + row),
                        (uint8_t)((g->col[8U + i] >> row) & 1U));
    }
  }

  /* ⚠ on == 0 时要"擦成黑"，上面写的是字模本身的像素（bit=1 处点亮）。
   * 若调用者要擦除，必须把字模取反。这里用取反再画一遍实现。 */
  if (on == 0U)
  {
    for (i = 0U; i < 8U; i++)
    {
      uint8_t row;

      for (row = 0U; row < 8U; row++)
      {
        SSD1306_DrawPixel((uint8_t)(x + i), (uint8_t)(y + row),
                          (uint8_t)(((g->col[i] >> row) & 1U) ^ 1U));
        SSD1306_DrawPixel((uint8_t)(x + i), (uint8_t)(y + 8U + row),
                          (uint8_t)(((g->col[8U + i] >> row) & 1U) ^ 1U));
      }
    }
  }
}

uint8_t SSD1306_DrawString(uint8_t x, uint8_t y, const char *s, uint8_t on)
{
  uint8_t cx = x;

  if (s == NULL)
  {
    return x;
  }

  while (*s != '\0')
  {
    if ((cx + 8U) > SSD1306_WIDTH)
    {
      break;                              /* 一行画满了就停，不换行 */
    }

    SSD1306_DrawChar(cx, y, *s, on);
    cx = (uint8_t)(cx + 8U);
    s++;
  }

  return cx;
}

