/* ---------------------------------------------------------------------------
 * I2C2 错误中断（ER）—— 手写补上
 *
 * 【为什么只有 ER 是手写的】.ioc 的 NVIC 页里只勾了 "I2C2 event interrupt"，
 * CubeMX 因此在上面（约 :220）自动生成了 I2C2_EV_IRQHandler。但 error
 * interrupt 没勾，所以 I2C2_ER_IRQHandler 得自己写。
 *
 * 【两者分工】
 *   EV：传完最后一个字节 -> TC 中断 -> 把 hi2c2.State 从 BUSY_TX 放回 READY。
 *   ER：总线出错（AF 应答失败 / BERR / ARLO 仲裁丢失 / OVR 溢出 / 总线超时）
 *       -> 清错误标志、把状态机踢回 READY、置 HAL_I2C_ERROR_xxx。
 *
 * 【少了 ER 的后果】一次 NACK 或一次总线毛刺就能让 hi2c2.State 永久卡在
 * BUSY —— 之后所有 I2C 操作（包括 PCF8574 的 ETH_RESET）统统 HAL_BUSY 失败。
 * 在 main() 里的表现就是 ETH_PHY_ReleaseReset() 返回非 0，板子停在
 * while(1) HAL_Delay(1000) 起不来。而 I2C 总线本来就有偶发 NACK 的可能，
 * 所以这不是理论风险。
 *
 * 【想一劳永逸】在 CubeMX 的 NVIC 页把 "I2C2 error interrupt" 也勾上，
 * 同时 Core/Src/i2c.c 的 USER CODE 区里补的 I2C2_ER_IRQn 使能就可以删掉，
 * 这个 Handler 也会由 CubeMX 生成 —— 那时请把本段连同函数一起删掉，
 * 否则又是重定义（I2C2_EV_IRQHandler 已经踩过这个坑）。
 * ------------------------------------------------------------------------- */
