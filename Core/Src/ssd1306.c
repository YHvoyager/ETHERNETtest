extern I2C_HandleTypeDef hi2c2;

/* ===========================================================================
 * 一、缓冲
 * ========================================================================= */

/**
  * @brief 图形缓冲：SSD1306 显存的镜像，页优先（buf[page*128 + x]）
  *
  * 为什么是 static 而不是栈上：1024 字节。STM32F429 的栈是 0x400 = 1024 字节
  * （见 startup_stm32f429xx.s），放栈上等于整个栈，必炸。
  */
static uint8_t s_gfx[SSD1306_GFX_SIZE];

/** 脏页位图：bit n = 第 n 页需要重传 */
static uint8_t s_dirty;

/** 发送缓冲：1 个控制字节 0x40（表示"后面是数据"）+ 一页 128 字节 */
static uint8_t s_tx[1U + SSD1306_WIDTH];

/** @brief 标记某一页为脏 */
static void mark_dirty(uint8_t page)
{
  if (page < SSD1306_PAGES)
  {
    s_dirty |= (uint8_t)(1U << page);
  }
}

void SSD1306_MarkAllDirty(void)
{
  s_dirty = 0xFFU;   /* 8 页，正好 8 个 bit */
}

/* ===========================================================================
 * 二、底层 I2C
 * ========================================================================= */

/**
  * @brief  写一串**命令**（控制字节 0x00）
  * @note   命令序列只在初始化时用，都很短（< 32 字节），直接借用 s_tx。
  *         但要小心：s_tx 的前 128 字节是数据区，写命令会覆盖它 ——
  *         所以初始化必须发生在任何 Flush 之前，代码顺序上也是这么排的。
  */
static int oled_cmd(const uint8_t *cmds, uint16_t n)
{
  if (n > SSD1306_WIDTH)
  {
    return -1;
  }

  s_tx[0] = 0x00U;                          /* Co=0, D/C#=0 → 后面全当命令 */
  memcpy(&s_tx[1], cmds, (size_t)n);

  if (HAL_I2C_Master_Transmit(&hi2c2, SSD1306_I2C_ADDR, s_tx,
                              (uint16_t)(1U + n), SSD1306_I2C_TIMEOUT) != HAL_OK)
  {
    return -1;
  }
  return 0;
}

/** @brief 写单条命令的便捷包装 */
static int oled_cmd1(uint8_t c)
{
  return oled_cmd(&c, 1U);
}

/* ===========================================================================
 * 三、初始化
 * ========================================================================= */

int SSD1306_Init(void)
{
  int rc;
  uint8_t col;

  /* ---- 1. 先确认屏在总线上 ----
   * 不用 HAL_I2C_IsDeviceReady：它对某些 SSD1306 模块（尤其是接了电平转换
   * 或复位电容较大的）会误判。直接写一条无害的命令试，能 ACK 就是活着。 */
  if (oled_cmd1(0xAEU) != 0)               /* Display OFF，上电本来就该关 */
  {
    printf("[OLED] FAIL: no ACK from 0x%02X -- check VCC/GND/SCL/SDA and pull-ups\r\n",
           SSD1306_I2C_ADDR);
    return -1;
  }

  /* ---- 2. 初始化序列 ----
   * 逐条都有理由，不要随手删：
   *   0xA8 0x3F  多路复用比 = 64 行（128x64 面板；改成 0x1F 就只显示上半屏）
   *   0xD3 0x00  显示偏移 0（有些模块不设会整体偏几行）
   *   0x40       显示起始行 = 0
   *   0x8D 0x14  电荷泵使能 —— **最关键的一条**。不开发光二极管不升压，
   *              屏就一直是黑的，I2C 却完全正常，非常难查
   *   0x20 0x00  内存寻址模式 = 页模式（本驱动按页传，必须这个）
   *   0xA1       段重映射：列 127 映射到 SEG0（不加整屏左右镜像）
   *   0xC8       扫描方向反向：行 63 → COM0（不加整屏上下颠倒）
   *   0xDA 0x12  COM 引脚配置：128x64 用交替配置；128x32 要改成 0x02
   *   0x81 0xCF  对比度（亮度）
   *   0xD9 0xF1  预充电周期
   *   0xDB 0x40  VCOMH 反压电平
   *   0xA4       输出跟随显存（0xA5 会强制全亮，用于测试）
   *   0xA6       正常显示（0xA7 是反色）
   *   0x2E       关掉滚动 */
  static const uint8_t init_seq[] = {
    0xAEU,                    /* display off */
    0xD5U, 0x80U,             /* clock divide / osc freq */
    0xA8U, 0x3FU,             /* multiplex ratio = 64 */
    0xD3U, 0x00U,             /* display offset = 0 */
    0x40U,                    /* display start line = 0 */
    0x8DU, 0x14U,             /* charge pump ON  ← 不开发光管不升压，屏全黑 */
    0x20U, 0x00U,             /* memory mode = page mode */
    0xA1U,                    /* segment remap */
    0xC8U,                    /* COM scan direction remapped */
    0xDAU, 0x12U,             /* COM pins config (128x64) */
    0x81U, 0xCFU,             /* contrast */
    0xD9U, 0xF1U,             /* pre-charge period */
    0xDBU, 0x40U,             /* VCOMH deselect level */
    0xA4U,                    /* entire display ON follows RAM */
    0xA6U,                    /* normal (not inverted) */
    0x2EU,                    /* deactivate scroll */
    0xAFU                     /* display ON */
  };

  rc = oled_cmd(init_seq, (uint16_t)sizeof(init_seq));
  if (rc != 0)
  {
    printf("[OLED] FAIL: init sequence write, I2C err=0x%08lX\r\n",
           (unsigned long)HAL_I2C_GetError(&hi2c2));
    return -2;
  }

  /* ---- 3. 清屏 ----
   * 初始化后显存内容是随机的，必须先清干净，否则上电就是一片雪花。
   * 先软件清 + 标全脏，再 Flush 一次推上去。 */
  SSD1306_Clear(0U);

  /* 顺便设一下列地址范围。页模式下次传输会自动回卷，
   * 但显式设一遍能保证第一页落在正确位置。 */
  oled_cmd1(0x21U); oled_cmd1(0x00U); oled_cmd1(0x7FU);   /* 列 0~127 */
  oled_cmd1(0x22U); oled_cmd1(0x00U); oled_cmd1(0x07U);   /* 页 0~7 */

  if (SSD1306_Flush() != 0)
  {
    printf("[OLED] FAIL: clear flush, I2C err=0x%08lX\r\n",
           (unsigned long)HAL_I2C_GetError(&hi2c2));
    return -3;
  }

  (void)col;
  printf("[OLED] SSD1306 128x64 ready at 0x%02X on I2C2 (PH4=SCL PH5=SDA)\r\n",
         SSD1306_I2C_ADDR);
  return 0;
}

/* ===========================================================================
 * 四、刷新（只传脏页）
 * ========================================================================= */

int SSD1306_Flush(void)
{
  uint8_t page;

  if (s_dirty == 0U)
  {
    return 0;                              /* 没有变化，一次总线都不占 */
  }

  s_tx[0] = 0x40U;                         /* Co=0, D/C#=1 → 后面全当显存数据 */

  for (page = 0U; page < SSD1306_PAGES; page++)
  {
    if ((s_dirty & (uint8_t)(1U << page)) == 0U)
    {
      continue;                            /* 这一页没变，跳过 */
    }

    /* 把光标定位到这一页的第 0 列。页模式下写满 128 字节会自动停在页尾，
     * 所以要重置列指针，否则第二页会从错误的位置开始。 */
    if (oled_cmd1((uint8_t)(0xB0U | page)) != 0)   /* 设置页起始行 */
    {
      return -1;
    }
    if (oled_cmd1(0x00U) != 0)                     /* 列低 4 位 = 0 */
    {
      return -1;
    }
    if (oled_cmd1(0x10U) != 0)                     /* 列高 4 位 = 0 */
    {
      return -1;
    }

    memcpy(&s_tx[1], &s_gfx[(uint16_t)page * SSD1306_WIDTH], SSD1306_WIDTH);

    if (HAL_I2C_Master_Transmit(&hi2c2, SSD1306_I2C_ADDR, s_tx,
                                (uint16_t)(1U + SSD1306_WIDTH),
                                SSD1306_I2C_TIMEOUT) != HAL_OK)
    {
      /* 只清掉**这一页**的脏标记会丢画面；整屏保持脏，下次重试。 */
      SSD1306_MarkAllDirty();
      return -(int)page - 2;               /* 带上是哪一页，便于定位 */
    }
  }

  s_dirty = 0U;
  return 0;
}

/* ===========================================================================
 * 五、绘图
 * ========================================================================= */

void SSD1306_Clear(uint8_t on)
{
  memset(s_gfx, (on != 0U) ? 0xFF : 0x00, sizeof(s_gfx));
  SSD1306_MarkAllDirty();
}

void SSD1306_DrawPixel(uint8_t x, uint8_t y, uint8_t on)
{
  uint8_t page;
  uint8_t bit;
  uint8_t mask;

  /* 越界静默丢弃：调用者画图时不用自己夹紧坐标，少一类 bug */
  if ((x >= SSD1306_WIDTH) || (y >= SSD1306_HEIGHT))
  {
    return;
  }

  page = (uint8_t)(y >> 3);                /* y / 8 → 第几页 */
  bit  = (uint8_t)(y & 0x07U);             /* y % 8 → 页内第几行 */
  mask = (uint8_t)(1U << bit);             /* ⚠ bit0 是页内最上面那行 */

  if (on != 0U)
  {
    s_gfx[(uint16_t)page * SSD1306_WIDTH + x] |= mask;
  }
  else
  {
    s_gfx[(uint16_t)page * SSD1306_WIDTH + x] &= (uint8_t)~mask;
  }

  mark_dirty(page);
}

uint8_t *SSD1306_GetBuffer(void)
{
  return s_gfx;
}

