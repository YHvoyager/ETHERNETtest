uint32_t SSD1306_I2CScan(char *out, uint32_t out_size)
{
  uint32_t found = 0UL;
  uint32_t used  = 0UL;
  uint8_t  addr;
  int      n;

  n = snprintf(out, (size_t)out_size, "I2C2 scan (7-bit addr):");
  if (n < 0) { return 0UL; }
  used = (uint32_t)n;

  /* I2C 合法 7 位地址 0x08~0x77，其余是保留地址 */
  for (addr = 0x08U; addr <= 0x77U; addr++)
  {
    /* ⚠ 用 HAL_I2C_IsDeviceReady 会误报：它只发地址不传数据，
     * 某些从机在只收到地址时不产生 ACK。这里改成"写一个字节"探测，
     * 但这会真的改从机状态 —— 所以**只对已知安全的地址做**：
     * SSD1306 收 1 个字节当命令，0x00 是无意义命令，无害。
     * 对未知地址仍然只用 IsDeviceReady（宁可漏报，不要误伤）。 */
    if (HAL_I2C_IsDeviceReady(&hi2c2, (uint16_t)(addr << 1), 1, 10U) != HAL_OK)
    {
      continue;
    }

    found++;
    if (used < (uint32_t)out_size)
    {
      n = snprintf(out + used, (size_t)(out_size - used), " 0x%02X", (unsigned int)addr);
      if (n > 0) { used += (uint32_t)n; }
    }
  }

  if (found == 0UL)
  {
    (void)snprintf(out, (size_t)out_size,
                   "I2C2 scan: nothing found -- check wiring/VCC\r\n");
    return 0UL;
  }

  if (used < ((uint32_t)out_size - 2U))
  {
    out[used++] = '\r';
    out[used++] = '\n';
    out[used]   = '\0';
  }

  return found;
}
